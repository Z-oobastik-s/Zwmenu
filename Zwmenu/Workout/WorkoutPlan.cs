    private static ExerciseImage Img(string file, string caption) => new(file, caption);

    private static Exercise Ex(
        string id, string name, string focus, string sets, string rest,
        string why, ExerciseImage[] images, string[] steps, string[] mistakes) =>
        new(id, name, focus, sets, rest, why, images,
            steps.Select(s => new ExerciseStep(s)).ToList(),
            mistakes);
