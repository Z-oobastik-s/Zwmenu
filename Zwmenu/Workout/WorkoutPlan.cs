namespace Zwmenu.Workout;

public sealed record ExerciseStep(string Text);

public sealed record ExerciseImage(string File, string Caption);

public sealed record Exercise(
    string Id,
    string Name,
    string Focus,
    string SetsReps,
    string Rest,
    string Why,
    IReadOnlyList<ExerciseImage> Images,
    IReadOnlyList<ExerciseStep> Steps,
    IReadOnlyList<string> Mistakes);

public sealed record WorkoutDay(
    string Key,
    string Title,
    string When,
    string Goal,
    IReadOnlyList<Exercise> Exercises);

